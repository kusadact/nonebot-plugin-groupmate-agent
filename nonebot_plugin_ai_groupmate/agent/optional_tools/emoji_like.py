DEFAULT_EMOJI_LIKE = EMOJI_LIKE_BY_MEANING["点赞"]


def _pick_emoji_by_meaning(meanings: tuple[str, ...]) -> EmojiLike:
    emojis = [EMOJI_LIKE_BY_MEANING[meaning] for meaning in meanings if meaning in EMOJI_LIKE_BY_MEANING]
    if not emojis:
        return DEFAULT_EMOJI_LIKE
    return random.choice(emojis)


def _resolve_emoji_like(emoji_name: str | None) -> EmojiLike:
    raw_name = str(emoji_name or "").strip()
    if not raw_name:
        return DEFAULT_EMOJI_LIKE

    normalized = raw_name.lower().strip("/[]()（） ")
    if raw_name in EMOJI_LIKE_BY_ID:
        return EMOJI_LIKE_BY_ID[raw_name]
    if normalized in EMOJI_LIKE_BY_ID:
        return EMOJI_LIKE_BY_ID[normalized]
    if raw_name in EMOJI_LIKE_BY_MEANING:
        return EMOJI_LIKE_BY_MEANING[raw_name]
    if normalized in EMOJI_LIKE_BY_NORMALIZED_MEANING:
        return EMOJI_LIKE_BY_NORMALIZED_MEANING[normalized]
    if normalized in EMOJI_LIKE_BY_CATEGORY:
        return random.choice(EMOJI_LIKE_BY_CATEGORY[normalized])

    alias = EMOJI_LIKE_ALIASES.get(normalized) or EMOJI_LIKE_ALIASES.get(raw_name)
    if alias:
        return _pick_emoji_by_meaning(alias)

    for emoji in EMOJI_LIKES:
        normalized_meaning = emoji.meaning.lower()
        if normalized and (normalized in normalized_meaning or normalized_meaning in normalized):
            return emoji

    return DEFAULT_EMOJI_LIKE


def extract_emoji_like_message_id_text(raw: str | None) -> str | None:
    text = str(raw or "").strip()
    match = re.search(r"\d+", text)
    return match.group() if match else None


def create_emoji_like_tool(
    session_id: str,
    request_id: str | None,
    bot_id: str | None,
    allowed_message_ids: set[str] | None = None,
):
    """Create the message reaction tool bound to the current request."""

    @tool("add_message_emoji_like")
    async def add_message_emoji_like(
        target_msg_id: str,
        emoji_name: str | None = None,
        reason: str | None = None,
    ) -> str:
        """
        给当前群聊中的一条消息添加 QQ/NapCat 评论表情。
        这是可选的轻量反应工具，不会发送新消息。

        参数:
        - target_msg_id: 目标消息 id，必须来自当前 prompt 中出现的消息 id。
        - emoji_name: 可选，可传具体表情名、表情 id、语义词或分类词。
        - reason: 可选，为什么给这条消息添加这个评论表情。
        """
        if request_id is not None and not await is_request_active(session_id, request_id):
            return "请求已过期，已取消评论表情。"
        if not bot_id:
            return "无法获取 bot ID，评论表情失败。"

        message_id_text = extract_emoji_like_message_id_text(target_msg_id)
        if message_id_text is None:
            return f"评论表情失败: 无法从 target_msg_id 中提取有效数字: {target_msg_id!r}"
        if allowed_message_ids is not None and message_id_text not in allowed_message_ids:
            return "评论表情失败: target_msg_id 不在本轮可评论表情候选消息里。"

        message_id = int(message_id_text)
        emoji = _resolve_emoji_like(emoji_name)

        try:
            bot = get_bot(bot_id)
            if not hasattr(bot, "call_api"):
                return "当前适配器不支持评论表情功能。"

            if request_id is not None and not await is_request_active(session_id, request_id):
                return "请求已过期，已取消评论表情。"

            await bot.call_api(
                "set_msg_emoji_like",
                message_id=message_id,
                emoji_id=emoji.id,
                set=True,
            )
            logger.info(
                "评论表情成功: session_id=%s message_id=%s emoji_id=%s emoji_name=%s category=%s reason=%s",
                session_id,
                message_id,
                emoji.id,
                emoji.meaning,
                emoji.category,
                reason or "",
            )
            return f"已给消息 {message_id} 添加评论表情“{emoji.meaning}”。"
        except Exception as e:
            logger.warning(
                "评论表情失败: session_id=%s message_id=%s emoji_id=%s emoji_name=%s error=%s",
                session_id,
                message_id,
                emoji.id,
                emoji.meaning,
                e,
            )
            return f"评论表情失败: {type(e).__name__}: {e}"

    return add_message_emoji_like


PROMPT_TEMPLATE = """- 评论表情：可选使用 `add_message_emoji_like`
  - 当你觉得某条消息适合轻量回应时，可以给它添加一个评论表情
  - 这是附加反应，不是必须；没有特别合适的消息就不要调用
  - 优先给【当前触发消息】或【本轮回复引用的消息】添加
  - `target_msg_id` 必须来自本轮 prompt 中出现的消息 id，不要猜
  - 不要为了完成任务硬贴表情，不要连续乱贴；每轮最多调用一次
  - `emoji_name` 可以传具体表情名、表情 id、语义词或分类词
  - 可用分类：{categories}
  - 选择表情时按语义匹配，例如：赞同用“赞同鼓励”，好笑用“好笑玩梗”，疑惑用“疑惑思考”，安慰用“安慰难过”
  - 喜欢亲近用“喜欢贴贴”，祝贺用“庆祝好运”，生气或拒绝用“生气拒绝”，惊讶或尴尬用“惊讶尴尬”
  - 如果 `add_message_emoji_like` 返回失败，不要假装成功；通常也不用专门解释
"""


async def build(ctx: OptionalToolContext) -> OptionalToolBundle:
    emoji_like_tool = create_emoji_like_tool(
        ctx.session_id,
        ctx.request_id,
        ctx.bot_id,
        ctx.emoji_like_candidate_ids,
    )
    return OptionalToolBundle(
        name="emoji_like",
        tools=[emoji_like_tool],
        prompt=PROMPT_TEMPLATE.format(categories=EMOJI_LIKE_CATEGORY_PROMPT),
        tool_limits=[ToolLimitSpec(tool_name="add_message_emoji_like", run_limit=1)],
    )
